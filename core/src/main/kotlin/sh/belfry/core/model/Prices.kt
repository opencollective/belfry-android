package sh.belfry.core.model

import java.text.NumberFormat
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter
import java.util.Currency
import java.util.Locale

// Ticket prices (collective-belfry docs/checkin.md "Ticket prices", "VAT and prices for a while";
// a port of the web's events.ts pricesOf / priceLabel / priceFull / priceLine). A priced ticket is
// never self-served: people ask, settle with the hosts, and a host's admission (a 9000 with
// ["paid","paid"]) says the price is settled. Belfry takes no money for tickets.

/** The price on now: "€50", maybe with VAT, until when (unix seconds). */
data class Price(val amount: String, val currency: String, val vat: String? = null, val vatIncluded: Boolean = false, val until: Long? = null)

/** One row of a ticket's prices: without dates (`price`) or for a while (`price_at`). */
data class PriceRow(val amount: String, val currency: String, val from: Long? = null, val until: Long? = null)

/** What a ticket costs now. [priced] = it has a price at all; [onSale] false = priced, nothing on now. */
data class TicketPrice(val price: Price?, val priced: Boolean, val prices: List<PriceRow>, val onSale: Boolean) {
    companion object { val FREE = TicketPrice(null, false, emptyList(), true) }
}

object Prices {
    private val AMOUNT = Regex("^\\d{1,7}(\\.\\d{1,2})?$")
    private val VAT_RATE = Regex("^\\d{1,2}(\\.\\d{1,2})?$")
    private val MONEY = Regex("^[A-Z]{3}$")
    private val CURRENCY = Regex("^[A-Za-z0-9][A-Za-z0-9 ]{0,11}$")
    private val TS = Regex("^\\d{9,11}$")

    fun isMoney(currency: String) = MONEY.matches(currency)

    /**
     * A readable (amount, currency), or null: the server's `_amount` (events.py at 09086a9).
     * "007.10" → "7.10", "12.5" → "12.50"; a 3-letter currency in capitals; HOUR / HOURS → "HOUR";
     * an own label (1–12 letters, digits, spaces) as written.
     */
    fun amount(rawIn: String, curIn: String): Pair<String, String>? {
        val raw = rawIn.trim()
        var cur = curIn.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }.joinToString(" ")
        if (!AMOUNT.matches(raw) || !CURRENCY.matches(cur)) return null
        val whole = raw.substringBefore('.')
        val frac = raw.substringAfter('.', "").trimEnd('0')
        val amount = whole.toLong().toString() + if (frac.isNotEmpty()) "." + frac.padEnd(2, '0') else ""
        cur = when {
            cur.uppercase(Locale.ROOT) == "HOUR" || cur.uppercase(Locale.ROOT) == "HOURS" -> "HOUR"
            Regex("^[A-Za-z]{3}$").matches(cur) -> cur.uppercase(Locale.ROOT)
            else -> cur
        }
        return amount to cur
    }

    private fun ts(x: String): Long? = if (TS.matches(x)) x.toLong() else null

    /**
     * What a ticket costs now: the server's `price_of` (collective-belfry events.py at 09086a9;
     * `vectors/ticket-prices.json`, generated by running it). No price tag, or a current amount
     * of zero = free. Anything unreadable = priced with no amount ("Paid"), never free. `price_at`
     * rows in tag order, the first current one wins, else the plain price (which holds until the
     * next dated row starts). Dated rows only and none now = not on sale. VAT only on a 3-letter
     * currency.
     */
    fun of(tags: List<List<String>>, now: Long): TicketPrice {
        val base = tags.firstOrNull { it.firstOrNull() == "price" }
        val dated = tags.filter { it.firstOrNull() == "price_at" }
        if (base == null && dated.isEmpty()) return TicketPrice.FREE
        var unreadable = false
        val rows = ArrayList<PriceRow>()
        for (t in dated) {
            val got = amount(t.getOrNull(1) ?: "", t.getOrNull(2) ?: "")
            val start = t.getOrNull(3)?.trim() ?: ""
            val end = t.getOrNull(4)?.trim() ?: ""
            if (got == null || (start.isNotEmpty() && ts(start) == null) || (end.isNotEmpty() && ts(end) == null)) { unreadable = true; continue }
            rows.add(PriceRow(got.first, got.second, ts(start), ts(end)))
        }
        if (base != null) {
            val got = amount(base.getOrNull(1) ?: "", base.getOrNull(2) ?: "")
            if (got == null) unreadable = true else rows.add(PriceRow(got.first, got.second))
        }
        if (unreadable) return TicketPrice(null, true, rows, true)
        val cur = rows.firstOrNull { (it.from == null || it.from <= now) && (it.until == null || now < it.until) }
            ?: return TicketPrice(null, true, rows, false)
        if ((cur.amount.toDoubleOrNull() ?: 0.0) == 0.0) return TicketPrice(null, false, rows, true)
        var until = cur.until
        if (cur.until == null && base != null && cur === rows.last()) {
            until = rows.dropLast(1).mapNotNull { it.from }.filter { it > now }.minOrNull()
        }
        var price = Price(cur.amount, cur.currency, until = until)
        val vat = tags.firstOrNull { it.firstOrNull() == "vat" }
        if (vat != null && isMoney(cur.currency)) {
            val rate = vat.getOrNull(1)?.trim() ?: ""
            if (VAT_RATE.matches(rate)) {
                price = price.copy(vat = if ('.' in rate) rate.trimEnd('0').trimEnd('.') else rate, vatIncluded = vat.getOrNull(2) == "included")
            }
        }
        return TicketPrice(price, true, rows, true)
    }

    /** "€15", "20 USD", "2 hours", "3 Time credits" (the server's price_text). */
    fun label(p: Price): String = when (p.currency) {
        "EUR" -> "€" + p.amount
        "HOUR" -> "${p.amount} ${if (p.amount == "1") "hour" else "hours"}"
        else -> "${p.amount} ${p.currency}"
    }

    /** "€50 + 21% VAT", "€50 incl. 21% VAT", "2 hours". */
    fun full(p: Price): String = label(p) + if (p.vat != null && isMoney(p.currency)) (if (p.vatIncluded) " incl. ${p.vat}% VAT" else " + ${p.vat}% VAT") else ""

    /** The words, without the "· until": "Free", "Paid" (unreadable), "Not on sale now", or the price (`vectors/ticket-prices.json` line). */
    fun words(t: TicketPrice): String = when {
        !t.priced -> "Free"
        !t.onSale -> "Not on sale now"
        t.price == null -> "Paid"
        else -> full(t.price)
    }

    private val DAY = DateTimeFormatter.ofPattern("d MMMM yyyy", Locale.ENGLISH)

    /** Under a ticket's name: "€50 + 21% VAT · until 1 January 2027", "Paid", "Not on sale now", or "" (free). */
    fun line(t: TicketPrice, zone: ZoneId): String = when {
        !t.priced -> ""
        else -> words(t) + (t.price?.until?.let { " · until " + DAY.format(Instant.ofEpochSecond(it).atZone(zone)) } ?: "")
    }
}
